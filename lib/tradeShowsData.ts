/**
 * Returns raw verified hotels for a venue, filtering by radius (<= maxRadiusKm)
 */
export function getHotelsForTradeShow(tradeShowId: string, maxRadiusKm = 7.0): ExtractedHotel[] {
  const all = RAW_TRADE_SHOW_HOTELS[tradeShowId] || [];
  return all
    .filter(h => h.distanceKm <= maxRadiusKm)
    .sort((a, b) => a.distanceKm - b.distanceKm);
}
